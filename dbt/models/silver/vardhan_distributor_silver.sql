{{ config(
    materialized='table',
    unique_key='distributor_stock_hash_key',
    schema='VARDHAN_SILVER'
) }}

WITH source_data AS (
    SELECT
        MD5(CONCAT_WS('||', 
            COALESCE(TRIM(SKU), ''), 
            COALESCE(TRIM(WAREHOUSE), '')
        )) AS DISTRIBUTOR_STOCK_HASH_KEY,
        TRIM(UPPER(SKU)) AS SKU_CODE,
        TRIM(DISTRIBUTOR_ITEM_NAME) AS DISTRIBUTOR_ITEM_NAME,
        TRIM(UPPER(WAREHOUSE)) AS WAREHOUSE_LOCATION,
        TRY_CAST(AVAILABLE_QTY AS INT) AS AVAILABLE_QTY,
        CAST(RATE AS NUMBER(38,2)) AS WHOLESALE_RATE,
        CAST(MRP AS NUMBER(38,2)) AS MRP,
        TRY_CAST(ITEM_UPDATED_AT AS TIMESTAMP_NTZ) AS ITEM_UPDATED_AT,
        TRY_CAST(PULLED_AT AS TIMESTAMP_NTZ) AS API_PULLED_AT,
        SOURCE_FILE,
        SOURCE_ROW_NUMBER,
        INGESTED_AT AS BRONZE_LOADED_AT,
        CURRENT_TIMESTAMP() AS SILVER_LOADED_AT
    FROM {{ source('VARDHAN_BRONZE', 'VARDHAN_DISTRIBUTOR_RAW') }}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SKU, WAREHOUSE 
        ORDER BY TRY_CAST(ITEM_UPDATED_AT AS TIMESTAMP_NTZ) DESC, INGESTED_AT DESC
    ) = 1
)

SELECT * FROM source_data