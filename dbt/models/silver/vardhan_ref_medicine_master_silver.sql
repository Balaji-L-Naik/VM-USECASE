WITH standardized AS (
    SELECT
        TRIM(UPPER(m.SKU)) AS SKU_CODE,
        TRIM(COALESCE(c.CORRECTED_NAME, m.MEDICINE_NAME)) AS MEDICINE_NAME,
        TRIM(UPPER(m.SCHEDULE)) AS SCHEDULE,
        TRIM(m.MANUFACTURER) AS MANUFACTURER,
        m.SOURCE_FILE,
        m.SOURCE_ROW_NUMBER,
        m.INGESTED_AT AS BRONZE_LOADED_AT
    FROM {{ source('VARDHAN_BRONZE', 'VARDHAN_REF_MEDICINE_MASTER_RAW') }} m
    LEFT JOIN {{ source('VARDHAN_BRONZE', 'VARDHAN_REF_MEDICINE_CORRECTIONS_RAW') }} c
        ON TRIM(LOWER(m.MEDICINE_NAME)) = TRIM(LOWER(c.INCORRECT_NAME))
        OR TRIM(LOWER(m.SKU)) = TRIM(LOWER(c.INCORRECT_NAME))
    WHERE COALESCE(m.SKU, m.MEDICINE_NAME) IS NOT NULL
      AND TRIM(COALESCE(m.SKU, m.MEDICINE_NAME)) != ''
)

SELECT
    MD5(COALESCE(NULLIF(SKU_CODE, ''), UPPER(MEDICINE_NAME))) AS MEDICINE_HASH_KEY,
    SKU_CODE,
    MEDICINE_NAME,
    SCHEDULE,
    MANUFACTURER,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    BRONZE_LOADED_AT,
    CURRENT_TIMESTAMP() AS SILVER_LOADED_AT
FROM standardized
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY COALESCE(NULLIF(SKU_CODE, ''), UPPER(MEDICINE_NAME))
    ORDER BY BRONZE_LOADED_AT DESC
) = 1
