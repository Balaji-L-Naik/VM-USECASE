{{ config(
    materialized='table',
    unique_key='stock_hash_key',
    schema='VARDHAN_SILVER'
) }}

WITH source_data AS (
    SELECT
        MD5(CONCAT_WS('||', 
            COALESCE(TRIM(UPPER(STORE_ID)), ''), 
            COALESCE(TRIM(UPPER(SKU)), ''), 
            COALESCE(TRIM(UPPER(BATCH_NO)), ''), 
            COALESCE(TRIM(SNAPSHOT_DATE::STRING), '')
        )) AS STOCK_HASH_KEY,
        TRIM(UPPER(STORE_ID)) AS STORE_ID,
        TRIM(UPPER(SKU)) AS SKU_CODE,
        TRIM(UPPER(BATCH_NO)) AS BATCH_NO,
        TRY_TO_DATE(TRIM(EXPIRY_DATE::STRING), 'YYYY-MM-DD') AS EXPIRY_DATE,
        TRY_CAST(TRIM(CLOSING_STOCK_QTY::STRING) AS INT) AS CLOSING_STOCK_QTY,
        TRY_TO_DATE(TRIM(SNAPSHOT_DATE::STRING), 'YYYY-MM-DD') AS SNAPSHOT_DATE,
        SOURCE_FILE,
        SOURCE_ROW_NUMBER,
        INGESTED_AT AS BRONZE_LOADED_AT,
        CURRENT_TIMESTAMP() AS SILVER_LOADED_AT
    FROM {{ source('VARDHAN_BRONZE', 'VARDHAN_POS_STOCK_RAW') }}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY STORE_ID, SKU, BATCH_NO, SNAPSHOT_DATE 
        ORDER BY INGESTED_AT DESC
    ) = 1
)

SELECT * FROM source_data